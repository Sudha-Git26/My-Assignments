function numbertype() {
    let numType = -10;

    if (numType > 0) {
        console.log("Given number is greater than 0", numType);
    } else if (numType < 0) {
        console.log("Given number is less than 0", numType);
    } else {
        console.log("Number is equal to zero", numType);
    }
}

numbertype();
